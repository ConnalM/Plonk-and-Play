// Drag design fixture checks; no production race engine or real browser layout.
const fs=require('node:fs'),path=require('node:path');
function test(script){
 const results=[],elements={},handlers={};
 const el=id=>elements[id]??={value:'',textContent:'',innerHTML:'',dataset:{},querySelectorAll:()=>[]};
 const document={getElementById:el,querySelectorAll:()=>[],addEventListener:(k,fn)=>handlers[k]=fn};
 const a=new Function('document',script+'\nreturn {signal,startTree,act,lamps,tree,run,setup,facts,avg,scaled,aux,results,track,s:()=>({phase,blocked,red,amber,reaction,et,history,treeType,role}),set:(k,v)=>{if(k==="tree")treeType=v;else if(k==="role")role=v;else if(k==="course")course=v;else if(k==="scale")scale=v}};')(document);
 const ck=(name,fn)=>{try{results.push({name,status:fn()?'PASS':'FAIL'})}catch(e){results.push({name,status:'ERROR',detail:String(e)})}};
 const phase=x=>a.s().phase===x;const sig=x=>a.signal(x);
 ck('two-sensor mapping',()=>a.track().includes('Sensor 1')&&a.track().includes('Sensor 2'));
 ck('Sportsman default',()=>a.s().treeType==='Sportsman');
 ck('PRE-STAGE dormant',()=>a.lamps()[0].dormant&&a.tree().includes('REU required'));
 ck('GO illegal before staging',()=>!sig('go'));
 ck('STAGE enters waiting',()=>a.act('stage')&&phase('waiting'));
 ck('waiting sensor blocks',()=>sig('block')&&phase('rollback')&&a.lamps()[1].on==='#fff5ad');
 ck('blocked cannot start',()=>!a.startTree());
 ck('clears to ready',()=>sig('clear')&&phase('ready'));
 ck('prestart reblock is rollback, not false start',()=>sig('cross')&&phase('rollback')&&!a.s().red);
 ck('second clear ready',()=>sig('clear')&&phase('ready'));
 ck('tree starts only when clear',()=>a.startTree()&&phase('tree'));
 ck('early GO rejected',()=>!sig('go'));
 ck('Sportsman amber 1',()=>sig('amber')&&a.s().amber===1&&a.lamps()[2].on==='#ffb000');
 ck('Sportsman amber 2',()=>sig('amber')&&a.s().amber===2&&a.lamps()[3].on==='#ffb000');
 ck('Sportsman amber 3',()=>sig('amber')&&a.s().amber===3&&a.lamps()[4].on==='#ffb000');
 ck('GO green',()=>sig('go')&&phase('go')&&a.lamps()[5].on==='#45d477');
 ck('start crossing starts ET, reaction separate',()=>sig('cross')&&phase('running')&&a.s().reaction===.23&&a.s().et===0);
 ck('running sample',()=>sig('live')&&a.run().includes('2.14 s'));
 ck('finish sample valid',()=>sig('finish')&&phase('result')&&a.s().et===6.84);
 ck('ET dominates valid result',()=>a.facts().includes('class="bigET">6.84 s')&&!a.facts().includes('class="redHero"'));
 ck('speed unavailable without course',()=>a.avg()==='—');
 ck('REU locked',()=>a.facts().includes('TRAP SPEED — REU required'));
 ck('results marked simulated',()=>a.results().includes('Session-local supplied review fixtures'));
 ck('history snapshot immutable',()=>a.s().history.length===1&&Object.isFrozen(a.s().history[0]));
 ck('no SAVE action',()=>!a.run().includes('data-action="save"'));
 ck('setup locked on completed run',()=>!a.setup().includes('id="course"'));
 ck('repeat finish rejected',()=>!sig('finish')&&a.s().history.length===1);
 ck('RACE AGAIN retains history',()=>a.act('again')&&phase('waiting')&&a.s().et===null&&a.s().history.length===1);
 ck('false start triggered after tree begins',()=>sig('block')&&sig('clear')&&a.startTree()&&sig('cross')&&a.s().red&&a.s().reaction===-.08);
 ck('red light dominant while running',()=>a.facts().includes('RED LIGHT'));
 ck('false start still records ET',()=>sig('finish')&&a.s().et===6.71&&a.facts().includes('RED LIGHT'));
 ck('second history status red',()=>a.s().history.length===2&&a.s().history[1].red);
 ck('new setup clears stale metrics',()=>a.act('new')&&phase('setup')&&a.s().et===null&&a.s().reaction===null);
 a.set('tree','Pro');a.set('course','10');a.set('scale','32');
 ck('speed not inferred for new setup',()=>a.avg()==='—');
 ck('Pro tree stage',()=>a.act('stage')&&sig('block')&&sig('clear')&&a.startTree());
 ck('Pro all ambers together',()=>sig('amber')&&a.s().amber===3&&[2,3,4].every(i=>a.lamps()[i].on==='#ffb000'));
 ck('Pro false start negative reaction',()=>sig('cross')&&a.s().red&&a.s().reaction===-.08);
 ck('Pro finish ET',()=>sig('finish')&&a.s().et===6.71);
 ck('whole-run average speed derived',()=>a.avg()===(10/6.71*2.236936292).toFixed(1)+' mph');
 ck('scale speed distinct from trap',()=>a.scaled()===(320/6.71*2.236936292).toFixed(1)+' mph');
 ck('auxiliary dedicated tree',()=>a.aux().includes('800 × 480')&&a.aux().includes('PRE-STAGE'));
 ck('view-only cannot stage',()=>{a.act('new');a.set('role','mug');return !a.act('stage')});
 ck('missing ET not silently replaced',()=>{a.set('role','director');a.act('stage');sig('block');sig('clear');a.startTree();sig('amber');sig('go');sig('cross');sig('finishMissing');return a.s().et===null&&a.avg()==='—'&&a.facts().includes('ET unavailable')});
 return results;
}
const html=fs.readFileSync(path.join(__dirname,'PP_Drag_review.html'),'utf8');
const rows=test(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
console.table(rows);if(rows.some(x=>x.status!=='PASS'))process.exitCode=1;
