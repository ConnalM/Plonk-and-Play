"""Set the canonical ESP app identity in the linked ELF before elf2image.

Arduino-ESP32 supplies a weak ``esp_app_desc`` object from its prebuilt
framework libraries.  The project owns the product identity, so this narrow
link-output hook updates the ELF's ``.flash.appdesc`` section before the
official Espressif elf2image step runs.  The final firmware image is therefore
generated by elf2image with its checksum and validation hash calculated from
the canonical ELF contents.
"""

from pathlib import Path
import os
import struct

from elftools.elf.elffile import ELFFile

Import("env")

CANONICAL_PRODUCT = b"plonk-and-play"
APP_DESC_MAGIC = 0xABCD5432
APP_DESC_SECTION = ".flash.appdesc"
PROJECT_NAME_OFFSET = 0x30
VERSION_OFFSET = 0x10
SECURE_VERSION_OFFSET = 0x04
APP_DESC_SIZE = 256


def patch_linked_app_descriptor(source, target, env):
    del source, env
    elf_path = Path(str(target[0]))

    with elf_path.open("rb") as stream:
        elf = ELFFile(stream)
        section = elf.get_section_by_name(APP_DESC_SECTION)
        if section is None or section["sh_size"] < APP_DESC_SIZE:
            raise RuntimeError("linked ELF has no complete .flash.appdesc section")
        section_offset = int(section["sh_offset"])
        section_data = section.data()[:APP_DESC_SIZE]

    magic = struct.unpack_from("<I", section_data, 0)[0]
    if magic != APP_DESC_MAGIC:
        raise RuntimeError("linked ESP app descriptor magic is missing")

    name = CANONICAL_PRODUCT + b"\0" * (32 - len(CANONICAL_PRODUCT))
    image = bytearray(elf_path.read_bytes())
    field_offset = section_offset + PROJECT_NAME_OFFSET
    image[field_offset : field_offset + 32] = name
    candidate_version = os.environ.get("PP_APP_DESCRIPTOR_VERSION", "").encode("ascii")
    if len(candidate_version) > 31:
        raise RuntimeError("PP_APP_DESCRIPTOR_VERSION exceeds ESP descriptor capacity")
    if candidate_version:
        version_offset = section_offset + VERSION_OFFSET
        image[version_offset : version_offset + 32] = candidate_version + b"\0" * (32 - len(candidate_version))
        struct.pack_into("<I", image, section_offset + SECURE_VERSION_OFFSET, 1)
    elf_path.write_bytes(image)

    with elf_path.open("rb") as stream:
        elf = ELFFile(stream)
        section = elf.get_section_by_name(APP_DESC_SECTION)
        observed = section.data()[PROJECT_NAME_OFFSET : PROJECT_NAME_OFFSET + 32]
    if observed != name:
        raise RuntimeError("canonical ESP app product was not written to the ELF")
    print("[BUILD] linked_elf_app_descriptor_product=plonk-and-play")
    if candidate_version:
        print(f"[BUILD] linked_elf_app_descriptor_version={candidate_version.decode('ascii')}")


env.AddPostAction("$BUILD_DIR/${PROGNAME}.elf", patch_linked_app_descriptor)
