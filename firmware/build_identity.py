"""Generate build provenance consumed by the firmware at compile time."""

from pathlib import Path
import subprocess

Import("env")

project_dir = Path(env["PROJECT_DIR"])
build_dir = Path(env.subst("$BUILD_DIR"))
generated_dir = build_dir / "generated" / "pp"
generated_dir.mkdir(parents=True, exist_ok=True)

try:
    commit = subprocess.check_output(
        ["git", "-C", str(project_dir), "rev-parse", "HEAD"],
        text=True,
        stderr=subprocess.DEVNULL,
    ).strip()
except (OSError, subprocess.CalledProcessError):
    commit = "unknown"

environment = str(env.get("PIOENV", "unknown"))
header = generated_dir / "build_identity_generated.h"
header.write_text(
    "#pragma once\n"
    "// Generated by firmware/build_identity.py; do not edit.\n"
    f'#define PP_BUILD_SOURCE_COMMIT "{commit}"\n'
    f'#define PP_BUILD_ENVIRONMENT "{environment}"\n',
    encoding="ascii",
)
env.Append(CPPPATH=[str(build_dir / "generated")])

